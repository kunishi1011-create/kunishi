  static Expense _e({
    required String id,
    required String userId,
    required int expenseDaysAgo,
    required ExpenseCategory category,
    required int amount,
    required String vendor,
    required String description,
    required PaymentMethod paymentMethod,
    String? department,
    String? projectName,
    String? notes,
    bool hasReceipt = false,
    required ExpenseStatus status,
    String? adminComment,
    int? submittedDaysAgo,
    int? approvedDaysAgo,
    int? settledDaysAgo,
  }) {
    final created = _d(submittedDaysAgo ?? expenseDaysAgo, hour: 9);
    return Expense(
      id: id,
      userId: userId,
      expenseDate: _d(expenseDaysAgo, hour: 0),
      category: category,
      amount: amount,
      vendor: vendor,
      description: description,
      paymentMethod: paymentMethod,
      department: department,
      projectName: projectName,
      notes: notes,
      receiptUrl: hasReceipt ? 'receipt_$id.jpg' : null,
      status: status,
      adminComment: adminComment,
      submittedAt:
          submittedDaysAgo == null ? null : _d(submittedDaysAgo, hour: 18),
      approvedAt: approvedDaysAgo == null ? null : _d(approvedDaysAgo, hour: 11),
      settledAt: settledDaysAgo == null ? null : _d(settledDaysAgo, hour: 15),
      createdAt: created,
      updatedAt: _d(
        settledDaysAgo ?? approvedDaysAgo ?? submittedDaysAgo ?? expenseDaysAgo,
        hour: 16,
      ),
      approverId: (approvedDaysAgo != null || settledDaysAgo != null)
          ? 'u_admin'
          : null,
      taxRate: 10,
    );
  }

